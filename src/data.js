function rng(seed) { let s = seed; return () => (s = (s * 9301 + 49297) % 233280) / 233280 - .5 }
// ряд из n значений вокруг level с шумом amp, сумма ровно total (поправка разнесена пропорционально)
function series(n, level, amp, total, seed, gaps = []) {
  const r = rng(seed), v = Array.from({ length: n }, (_, i) => gaps.includes(i) ? null : level * (1 + r() * amp));
  const sum = v.reduce((a, x) => a + (x ?? 0), 0), k = total / sum;
  const out = v.map(x => x === null ? null : Math.round(x * k));
  const diff = total - out.reduce((a, x) => a + (x ?? 0), 0);
  const last = out.findLastIndex(x => x !== null); out[last] += diff;
  return out;
}

