// Прогон MVP: все экраны + полный маршрут приёмки; скриншоты в .taste-skill/e2e, ошибки консоли в выводе.
import { Browser, sleep } from 'file:///C:/Users/o.raiganiyev/.claude/skills/design-taste-frontend/scripts/lib/cdp.mjs';
import { mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const W = +(process.env.W || 1440), H = +(process.env.H || 900), out = '.taste-skill/e2e' + (process.env.W ? '-' + W : '');
mkdirSync(out, { recursive: true });
const url = pathToFileURL(process.cwd() + '/energokontur.html').href;
const b = await Browser.launch({ width: W, height: H }); const p = await b.newPage({ width: W, height: H });
if (W < 800) await p.setViewport({ width: W, height: H, dsf: 1, mobile: true });
await p.goto(url + '#/overview', { settleMs: 700 });
await p.eval(`(()=>{window.__err=[];const o=console.error;console.error=(...a)=>{__err.push(a.join(' '));o(...a)};const w=console.assert;console.assert=(c,...a)=>{if(!c)__err.push('assert '+a.join(' '))};return 1})()`);
const shot = async n => { await sleep(500); await p.screenshot({ path: `${out}/${n}.jpg`, quality: 80 }); };
const go = async h => { await p.eval(`location.hash=${JSON.stringify(h)}`); await sleep(350) };
await shot('01-overview');
await go('#/circuits/EC-01'); await shot('02-ec01-stage0');
const ev = s => p.eval(s);
await ev(`EK.act(0,'repair')`); await sleep(1600); await shot('03-ec01-stage1');
for (const k of ['meter','comparable','system']) await ev(`EK.setCheck(0,'${k}',true)`);
await shot('04-ec01-checks');
await ev(`EK.act(0,'technical')`); await shot('05-ec01-stage2');
await ev(`EK.setCheck(0,'variable',true)`); await ev(`EK.act(0,'accept')`); await shot('06-ec01-accepted');
await go('#/circuits/EC-02'); await ev(`EK.act(1,'repair')`); await ev(`EK.setCheck(1,'comparable',true)`); await shot('07-ec02');
await ev(`EK.act(1,'close')`); await shot('08-ec02-closed');
await go('#/circuits/EC-03'); await ev(`EK.act(2,'repair')`); await ev(`EK.act(2,'request')`); await shot('09-ec03');
await go('#/overview'); await shot('10-overview-after');
await go('#/economics'); await shot('11-economics');
await go('#/rollout'); await shot('12-rollout');
await go('#/journal'); await shot('13-journal');
await go('#/sources'); await shot('14-sources');
console.log('state', JSON.stringify(await ev(`EK.state.cases.map(c=>[c.stage,c.closed,c.requested])`)));
console.log('errors', JSON.stringify(p.consoleErrors), JSON.stringify(await ev('window.__err')));
await b.close();
